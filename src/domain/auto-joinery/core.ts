/** A top reaching past the carcass front (top over the fronts), seen as if it ended at the carcass front: its joints are laid out on that. */
export function withoutFrontOverhang(part: Part): Part {
  const overhang = part.meta?.frontOverhang ?? 0;
  return overhang > 0
    ? { ...part, thickness: part.thickness - overhang, position: { ...part.position, z: part.position.z - overhang / 2 } }
    : part;
}

/** Moves ops laid out on `withoutFrontOverhang(part)` onto the real part: its depth coordinates count from its own front edge. */
export function shiftOpsForFrontOverhang(part: Part, ops: DrillOperation[]): DrillOperation[] {
  const overhang = part.meta?.frontOverhang ?? 0;
  if (overhang <= 0) return ops;
  return ops.map((op) => (
    op.face === 'top' || op.face === 'bottom'
      ? { ...op, y: op.y + overhang }
      : op.face === 'left' || op.face === 'right'
        ? { ...op, x: op.x + overhang }
        : op
  ));
}
