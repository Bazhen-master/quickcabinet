// Шаг между крепёжными точками вдоль торца, выведенный из эталона 26163: торец 325
// несёт 2 пары, 550 — три, 810 — четыре, и промежуток между центрами держится в
// пределах 190–225 мм. Точки раскладываются равномерно между передним и задним
// центром. На торце 508 эталон сам непоследователен (трижды две пары, once три),
// так что там любое правило разойдётся с частью деталей.
const CAM_DOWEL_MAX_STEP = 200;

/** Центры крепёжных пар: передний, задний и равномерно распределённые между ними. */
function getCamDowelCenters(frontCenter: number, backCenter: number) {
  const span = backCenter - frontCenter;
  if (span <= 0) return [frontCenter];
  const gaps = Math.max(1, Math.round(span / CAM_DOWEL_MAX_STEP));
  return Array.from({ length: gaps + 1 }, (_, index) => frontCenter + (span * index) / gaps);
}

export function getCamDowelPairs(depth: number, rules: AutoJointRuleDraft) {
  const [frontCenter, backCenter] = clampOffsets(depth, rules.frontOffset, rules.backOffset);
  const halfSpacing = Math.max(8, rules.camDowelSpacing / 2);
  const clampX = (value: number) => Math.max(9, Math.min(depth - 9, value));
  const detailCenter = depth / 2;
  return getCamDowelCenters(frontCenter, backCenter).map((center) => {
    const dowelTowardCenter = center <= detailCenter;
    return {
      camX: clampX(center + (dowelTowardCenter ? -halfSpacing : halfSpacing)),
      dowelX: clampX(center + (dowelTowardCenter ? halfSpacing : -halfSpacing)),
    };
  });
}

export function getShelfCamDowelPairs(shelf: Part, rules: AutoJointRuleDraft, side: 'left' | 'right') {
  const centers = getShelfDepthOffsets(shelf, rules, side);
  const halfSpacing = Math.max(8, rules.camDowelSpacing / 2);
  const clampDepth = (value: number) => Math.max(9, Math.min(shelf.thickness - 9, value));
  const depthCenter = getShelfDrillReferenceDepth(shelf) / 2;
  return centers.map((center) => {
    const dowelTowardCenter = center <= depthCenter;
    return {
      camX: clampDepth(center + (dowelTowardCenter ? -halfSpacing : halfSpacing)),
      dowelX: clampDepth(center + (dowelTowardCenter ? halfSpacing : -halfSpacing)),
    };
  });
}

