export function isSectionBackPanel(sourceId?: string) {
  return typeof sourceId === 'string' && sourceId.startsWith('section-back-panel:');
}

export function parseSectionBackPanelSource(sourceId?: string | null) {
  if (!isSectionBackPanel(sourceId ?? undefined)) return null;
  // section-back-panel:<tierId>:<sectionId>[:<zoneId>]
  const [, tierId, sectionId, ...zoneParts] = (sourceId ?? '').split(':');
  const zoneId = zoneParts.length > 0 ? zoneParts.join(':') : undefined;
  return tierId && sectionId ? { tierId, sectionId, zoneId } : null;
}

